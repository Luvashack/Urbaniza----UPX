CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE regioes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL UNIQUE,
    descricao TEXT,
    area GEOMETRY(MULTIPOLYGON, 4326)
);

CREATE TABLE bairros (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    cidade TEXT NOT NULL DEFAULT 'Sorocaba',
    estado TEXT NOT NULL DEFAULT 'SP',
    regiao_id BIGINT NOT NULL,
    area GEOMETRY(MULTIPOLYGON, 4326),
    CONSTRAINT fk_bairro_regiao
        FOREIGN KEY (regiao_id) REFERENCES regioes(id)
        ON DELETE RESTRICT
);

CREATE TABLE categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL UNIQUE,
    descricao TEXT
);

CREATE TABLE avaliacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bairro_id BIGINT NOT NULL,
    categoria_id BIGINT NOT NULL,
    nota INTEGER NOT NULL CHECK (nota BETWEEN 1 AND 10),
    comentario TEXT,
    localizacao GEOGRAPHY(POINT, 4326) NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    CONSTRAINT fk_avaliacao_bairro
        FOREIGN KEY (bairro_id) REFERENCES bairros(id) ON DELETE RESTRICT,
    CONSTRAINT fk_avaliacao_categoria
        FOREIGN KEY (categoria_id) REFERENCES categorias(id) ON DELETE RESTRICT
);

CREATE INDEX idx_bairros_regiao ON bairros(regiao_id);
CREATE INDEX idx_avaliacoes_bairro ON avaliacoes(bairro_id);
CREATE INDEX idx_avaliacoes_categoria ON avaliacoes(categoria_id);
CREATE INDEX idx_avaliacoes_localizacao ON avaliacoes USING GIST(localizacao);
CREATE INDEX idx_bairros_area ON bairros USING GIST(area);
CREATE INDEX idx_regioes_area ON regioes USING GIST(area);

