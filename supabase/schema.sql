CREATE OR REPLACE FUNCTION identificar_bairro(
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION
)
RETURNS TABLE (
    bairro_id BIGINT,
    bairro_nome TEXT,
    regiao_id BIGINT,
    regiao_nome TEXT
)
LANGUAGE SQL
AS $$
    SELECT b.id, b.nome, r.id, r.nome
    FROM bairros b
    INNER JOIN regioes r ON r.id = b.regiao_id
    WHERE ST_Contains(
        b.area,
        ST_SetSRID(ST_MakePoint(longitude, latitude), 4326)
    )
    LIMIT 1;
$$;

CREATE OR REPLACE VIEW indicadores_bairros AS
WITH dados AS (
    SELECT
        b.id AS bairro_id,
        b.nome AS bairro,
        r.id AS regiao_id,
        r.nome AS regiao,
        COUNT(a.id) AS quantidade_avaliacoes,
        AVG(a.nota) AS media_nota
    FROM bairros b
    INNER JOIN regioes r ON r.id = b.regiao_id
    LEFT JOIN avaliacoes a ON a.bairro_id = b.id
    GROUP BY b.id, b.nome, r.id, r.nome
),
media_geral AS (
    SELECT AVG(nota) AS media_cidade FROM avaliacoes
),
ajuste AS (
    SELECT d.*, m.media_cidade, 20 AS minimo_avaliacoes
    FROM dados d CROSS JOIN media_geral m
)
SELECT
    bairro_id,
    bairro,
    regiao_id,
    regiao,
    quantidade_avaliacoes,
    ROUND(media_nota::NUMERIC, 2) AS media_nota,
    ROUND(
        (
            (COALESCE(media_nota, media_cidade) * quantidade_avaliacoes)
            + (media_cidade * minimo_avaliacoes)
        )
        / NULLIF(quantidade_avaliacoes + minimo_avaliacoes, 0)::NUMERIC,
        2
    ) AS media_ajustada,
    ROUND(
        (
            10 -
            (
                (
                    (COALESCE(media_nota, media_cidade) * quantidade_avaliacoes)
                    + (media_cidade * minimo_avaliacoes)
                )
                / NULLIF(quantidade_avaliacoes + minimo_avaliacoes, 0)
            )
        )::NUMERIC,
        2
    ) AS indice_criticidade
FROM ajuste;

